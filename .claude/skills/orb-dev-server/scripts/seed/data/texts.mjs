// ノート本文の種類と割合 (API の段と、Task 3 の SQL の段で共通にする)
//   普通の文 55% / MFM 12% / ハッシュタグ 12% / CW 8% / カスタム絵文字 13%
// rnd は createRandom の戻り値、emojiNames は本文に使えるローカルのカスタム絵文字名の配列。
// 戻り値は { text, cw } (cw は無ければ null)。
export function composeNote(rnd, emojiNames) {
	const r = rnd.next();
	if (r < 0.55) return { text: rnd.pick(SHORT_TEXTS), cw: null };
	if (r < 0.67) return { text: rnd.pick(MFM_TEXTS), cw: null };
	if (r < 0.79) return { text: `${rnd.pick(SHORT_TEXTS)} #${rnd.pick(HASHTAGS)}`, cw: null };
	if (r < 0.87) return { text: rnd.pick(SHORT_TEXTS), cw: rnd.pick(CW_TEXTS) };
	if (emojiNames.length === 0) return { text: rnd.pick(SHORT_TEXTS), cw: null };
	return { text: `${rnd.pick(SHORT_TEXTS)} :${rnd.pick(emojiNames)}:`, cw: null };
}
